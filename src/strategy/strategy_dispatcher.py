from collections import defaultdict
from typing import Iterable

from .strategy_context import StrategyContext
from .strategy_interface import Strategy
from .strategy_output import StrategyOutput
from .strategy_requirements import StrategyRequirements


class StrategyDispatcher:
    """
    Routes prepared market-data inputs to eligible strategy instances.

    The dispatcher is responsible for:
        - finding eligible strategies
        - invoking strategies
        - collecting strategy outputs

    The dispatcher does not:
        - create strategies
        - contain strategy business logic
        - manage users
        - perform risk checks
        - execute orders
        - publish events
    """

    def __init__(
        self,
        strategies: Iterable[Strategy] = (),
    ) -> None:
        self._strategies: list[Strategy] = list(strategies)

        self._context_routes: dict[
            tuple[str, str],
            list[Strategy],
        ] = defaultdict(list)

        self._tick_routes: dict[
            str,
            list[Strategy],
        ] = defaultdict(list)

        self._build_routes()

    def _build_routes(self) -> None:
        """
        Build routing indexes from strategy requirements.
        """
        self._context_routes.clear()
        self._tick_routes.clear()

        for strategy in self._strategies:
            requirements = strategy.get_requirements()

            self._register_context_routes(
                strategy,
                requirements,
            )

            if requirements.requires_ticks:
                self._tick_routes[
                    strategy.symbol
                ].append(strategy)

    def _register_context_routes(
        self,
        strategy: Strategy,
        requirements: StrategyRequirements,
    ) -> None:
        """
        Register a strategy for every candle timeframe it requires.
        """
        for timeframe in requirements.candle_timeframes:
            self._context_routes[
                (strategy.symbol, timeframe)
            ].append(strategy)

    def dispatch_context(
        self,
        context: StrategyContext,
    ) -> list[StrategyOutput]:
        """
        Dispatch a completed context to eligible strategies.

        Returns every signal/output generated by those strategies.
        """
        outputs: list[StrategyOutput] = []

        strategies = self._context_routes.get(
            (context.symbol, context.timeframe),
            [],
        )

        for strategy in strategies:
            output = strategy.on_context(context)

            if output is not None:
                outputs.append(output)

        return outputs

    def dispatch_tick(
        self,
        context: StrategyContext,
    ) -> list[StrategyOutput]:
        """
        Dispatch tick data only to strategies that require ticks.

        Returns every signal/output generated by those strategies.
        """
        outputs: list[StrategyOutput] = []

        strategies = self._tick_routes.get(
            context.symbol,
            [],
        )

        for strategy in strategies:
            output = strategy.on_tick(context)

            if output is not None:
                outputs.append(output)

        return outputs